import crypto from 'crypto';
import mongoose from 'mongoose';
import { config } from '../config/env';
import { hashPassword } from '../utils/cryptoAuth';
import { User, ADMIN_EMAIL, SEED_USERS } from '../models/UserModel';
import { recordAuditLog } from '../models/AuditLogModel';

/**
 * Secure One-Time CycloneGuard Admin Bootstrap & Password Reset CLI
 *
 * Usage:
 *   npx tsx src/scripts/bootstrap-admin.ts
 *   ADMIN_PASSWORD=MySecurePassword2026! npx tsx src/scripts/bootstrap-admin.ts
 *   npx tsx src/scripts/bootstrap-admin.ts --password=MySecurePassword2026! --email=admin@cycloneguard.tn.gov.in
 */
async function bootstrapAdmin() {
  console.log('================================================================');
  console.log(' CycloneGuard Secure Admin Bootstrap & Password Reset Utility');
  console.log('================================================================\n');

  // Parse command line flags if provided
  const args = process.argv.slice(2);
  let cliEmail: string | undefined;
  let cliPassword: string | undefined;

  for (const arg of args) {
    if (arg.startsWith('--email=')) {
      cliEmail = arg.split('=')[1]?.trim();
    } else if (arg.startsWith('--password=')) {
      cliPassword = arg.split('=')[1]?.trim();
    }
  }

  // Resolve Admin Email
  const targetEmail = (
    cliEmail ||
    process.env.ADMIN_EMAIL ||
    config.auth.adminEmail ||
    'admin@cycloneguard.tn.gov.in'
  ).toLowerCase().trim();

  // Resolve Admin Password
  let plainPassword =
    cliPassword ||
    process.env.ADMIN_INITIAL_PASSWORD ||
    process.env.ADMIN_PASSWORD;

  let isAutoGenerated = false;
  if (!plainPassword) {
    // Generate cryptographically secure random password if none was supplied
    plainPassword = `Admin@${crypto.randomBytes(9).toString('base64url')}!26`;
    isAutoGenerated = true;
  }

  if (plainPassword.length < 8) {
    console.error('[Error] Admin password must be at least 8 characters long for security compliance.');
    process.exit(1);
  }

  console.log(`[Config] Target Admin Email:     ${targetEmail}`);
  console.log(`[Config] Password Source:        ${isAutoGenerated ? 'Generated Secure One-Time Token' : 'Environment Variable / CLI Argument'}`);
  console.log(`[Config] Cryptographic Algorithm: PBKDF2 with HMAC-SHA512 (10,000 iterations, 16-byte random salt)`);

  // Compute PBKDF2 hash using existing cryptographic utility
  const { hash, salt } = hashPassword(plainPassword);

  // 1. Update in-memory seed account
  const existingSeed = SEED_USERS.find((u) => u.email.toLowerCase() === targetEmail);
  if (existingSeed) {
    existingSeed.passwordHash = hash;
    existingSeed.passwordSalt = salt;
    console.log('[In-Memory] Updated in-memory seed admin account.');
  }

  // 2. Persist to MongoDB if configured/reachable
  let mongoPersisted = false;
  try {
    console.log('[MongoDB] Checking database persistence...');
    await mongoose.connect(config.mongodb.uri, {
      dbName: config.mongodb.dbName,
      serverSelectionTimeoutMS: 3000,
      connectTimeoutMS: 3000,
    });

    const userDoc = await User.findOneAndUpdate(
      { email: targetEmail },
      {
        name: 'State Disaster Operations Chief (Admin)',
        email: targetEmail,
        passwordHash: hash,
        passwordSalt: salt,
        role: 'ADMIN',
        assignedDistrict: 'ALL',
        isActive: true,
        updatedAt: new Date(),
      },
      { upsert: true, new: true, setDefaultsOnInsert: true }
    );

    if (userDoc) {
      mongoPersisted = true;
      console.log(`[MongoDB] Successfully upserted Admin record in '${config.mongodb.dbName}.users' collection.`);
    }

    await mongoose.disconnect();
  } catch (err: any) {
    console.log(`[MongoDB] Note: MongoDB connection skipped or unavailable (${err.message}). In-memory operational fallback active.`);
  }

  // 3. Log Audit Trail
  recordAuditLog({
    actorEmail: targetEmail,
    actorRole: 'ADMIN',
    action: 'ADMIN_BOOTSTRAP',
    targetResource: 'SYSTEM_ADMIN_CREDENTIALS',
    status: 'SUCCESS',
    details: `Admin account bootstrap completed. Persisted in Mongo: ${mongoPersisted}`,
    ipAddress: '127.0.0.1 (CLI)',
  });

  console.log('\n================================================================');
  console.log(' Admin Bootstrap Completed Successfully ✅');
  console.log('================================================================');
  console.log(`\nAuthorized Admin Email:  ${targetEmail}`);
  if (isAutoGenerated) {
    console.log(`Generated Admin Password: ${plainPassword}`);
    console.log('\nIMPORTANT: Save this password immediately. To persist across backend restarts,');
    console.log(`add the following line to your 'backend/.env' file:`);
    console.log(`ADMIN_PASSWORD=${plainPassword}`);
  } else {
    console.log(`Admin Password:          [CONFIGURED VIA ENVIRONMENT VARIABLE]`);
  }
  console.log('\nTo authenticate via API:');
  console.log(`POST /api/auth/login`);
  console.log(`Payload: { "email": "${targetEmail}", "password": "<YOUR_PASSWORD>" }\n`);
}

bootstrapAdmin().catch((err) => {
  console.error('[Fatal Error] Admin bootstrap failed:', err);
  process.exit(1);
});
